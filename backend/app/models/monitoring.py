class PlanComponentDiffItem(BaseModel):
    """
    Detailed difference record for a specific plan component between plan versions.
    """
    category: str  # "Resource", "Shelter", "Healthcare", "Volunteer", "Transport", "Route", "Conflict"
    entity_id: str
    entity_name: str
    diff_type: str  # "ADDED", "REMOVED", "CHANGED", "UNCHANGED"
    previous_value: Optional[Any] = None
    new_value: Optional[Any] = None
    reason: Optional[str] = None
    requires_officer_attention: bool = False


class PlanDiffResult(BaseModel):
    """
    Deterministic comparison summary between previous response plan and revised response plan.
    """
    previous_plan_id: str
    previous_version: int
    new_plan_id: str
    new_version: int
    summary: str
    items: List[PlanComponentDiffItem] = Field(default_factory=list)
    affected_domains: List[OperationalDomain] = Field(default_factory=list)
    affected_agents: List[AgentName] = Field(default_factory=list)
    has_conflicts: bool = False
    is_material_change: bool = True
    generated_at: datetime = Field(default_factory=datetime.utcnow)


class ReplanningTriggerMetadata(BaseModel):
    """
    Lineage metadata linking a revised Coordination Plan to its triggering event and impact.
    """
    trigger_event_id: str
    impact_id: str
    previous_plan_id: str
    previous_version: int
    reasons: List[str] = Field(default_factory=list)
    material_change: bool = True


class PlanApprovalRequest(BaseModel):
    """
    Payload sent by Emergency Officer to approve and activate a revised response plan.
    """
    officer_notes: Optional[str] = None
    expected_state_fingerprint: Optional[str] = None


class PlanModifyRequest(BaseModel):
    """
    Payload sent by Emergency Officer to modify operational values in a revised response plan.
    """
    notes: Optional[str] = None
    modified_needs: Optional[List[Dict[str, Any]]] = None
    modified_allocations: Optional[List[Dict[str, Any]]] = None
    modified_shelters: Optional[List[Dict[str, Any]]] = None
    modified_facilities: Optional[List[Dict[str, Any]]] = None
    modified_volunteers: Optional[List[Dict[str, Any]]] = None
    modified_transports: Optional[List[Dict[str, Any]]] = None
    modified_routes: Optional[List[Dict[str, Any]]] = None


class PlanRejectRequest(BaseModel):
    """
    Payload sent by Emergency Officer to reject a revised response plan.
    """
    rejection_reason: str
    officer_notes: Optional[str] = None


class PlanActivationResponse(BaseModel):
    """
    Authoritative response after plan approval and activation.
    """
    success: bool
    plan_id: str
    version: int
    status: str
    previous_plan_id: Optional[str] = None
    previous_version: Optional[int] = None
    activated_at: datetime
    officer_id: str
    officer_name: str
    message: str

